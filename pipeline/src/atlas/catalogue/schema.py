"""Exports the catalogue models to JSON Schema, the contract with the web app."""

import json
from pathlib import Path

from pydantic import BaseModel

from atlas.catalogue.models import DatasetsFile, FactorsFile, Region
from atlas.publish.manifest import Manifest

SCHEMAS: dict[str, type[BaseModel]] = {
    "factors.schema.json": FactorsFile,
    "datasets.schema.json": DatasetsFile,
    "region.schema.json": Region,
    "manifest.schema.json": Manifest,
}
COMMENT = "Generated by `just generate` from pipeline/src/atlas/catalogue/models.py. Do not edit."


def write_schemas(directory: Path) -> list[Path]:
    """Writes each schema into `directory`, with Unix line endings so that git sees no change."""
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for file_name, model in SCHEMAS.items():
        schema = {"$comment": COMMENT, **model.model_json_schema()}
        path = directory / file_name
        text = json.dumps(schema, indent=2, ensure_ascii=False) + "\n"
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written
